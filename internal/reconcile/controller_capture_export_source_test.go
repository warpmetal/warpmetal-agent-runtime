package reconcile

import (
	"encoding/json"
	"os"
	"path/filepath"
	"reflect"
	"testing"

	"github.com/warpmetal/warpmetal-agent-runtime/internal/model"
)

// Explicit transport-fixture export only. Reuses the existing declared SOURCE
// DATA constructor against an unchanged retained native output and input. No
// authority/signature generation, normal Reconcile, process or provider run.
func exportCurrentControllerCaptureSource(t *testing.T, source, destination string) {
	t.Helper()
	if !filepath.IsAbs(source) || !filepath.IsAbs(destination) || filepath.Base(source) != "current-manager-accept-observation.json" {
		t.Fatal("exact retained SOURCE observation/export paths required")
	}
	raw, err := os.ReadFile(source)
	var retained struct {
		Operation model.ControllerOutputOperation `json:"operation"`
		Proof     model.ControllerOutputEnvelope  `json:"proof"`
	}
	if err != nil || json.Unmarshal(raw, &retained) != nil {
		t.Fatal("retained SOURCE original", err)
	}
	output := retained.Proof.Payload.NativeReceipt.NativeReadback
	input := retained.Operation.Lineage.InputText
	capture := sourceCurrentParentCapture(t, &firstTaskPublicDeliveryFixture{root: filepath.Dir(source)}, output, input)
	lineage, err := capture.Verify(input, output.Data.ControllerOutput.Identity, output.Data.ControllerOutput.Admission)
	if err != nil || !reflect.DeepEqual(lineage, retained.Operation.Lineage) {
		t.Fatal("SOURCE export changed retained lineage", err)
	}
	if err := os.Mkdir(destination, 0700); err != nil {
		t.Fatal("immutable fresh export directory", err)
	}
	write := func(name string, value any) string {
		encoded := fixtureRaw(value)
		if err := os.WriteFile(filepath.Join(destination, name), encoded, 0600); err != nil {
			t.Fatal(err)
		}
		return model.RawPhysicalDigest(encoded)
	}
	outputDigest := write("native-output.json", capture.NativeOutput)
	logDigest := write("native-log.json", capture.NativeLog)
	observationDigest := write("controller-output-observation.json", map[string]any{"schemaVersion": 1, "command": "controller-output", "status": "observed", "nativeOutput": capture.NativeOutput, "nativeLog": capture.NativeLog})
	write("source-input.json", map[string]any{"inputText": input, "lineage": lineage})
	write("receipt.json", map[string]any{"classification": "SOURCE transport fixture: unchanged retained nativeOutput/input; DATA regenerated by existing sourceCurrentParentCapture and verified by owning capture.Verify; no actual native capture or new authority", "sourcePath": source, "sourceDigest": model.RawPhysicalDigest(raw), "nativeOutputDigest": outputDigest, "nativeLogDigest": logDigest, "observationDigest": observationDigest, "sourceSessionId": output.Data.ControllerOutput.Lineage.SessionID, "inputId": output.Data.ControllerOutput.Lineage.InputID, "logRecords": len(capture.NativeLog), "providerCalls": 0, "nativeRuns": 0, "rootRuns": 0, "normalReconcileRuns": 0})
	t.Log("bounded unchanged-output SOURCE DATA export verified; no normal acceptance/native/provider/ROOT", destination)
}
